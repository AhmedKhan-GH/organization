// Generates site/design/sternbild.css from design/tokens.json.
//
//   node design/build.mjs           write the CSS
//   node design/build.mjs --check   exit 1 if the committed CSS is out of date
//
// Plain Node (18 or later), no dependencies. Each token becomes a CSS custom property named
// --<prefix>-<path joined by hyphens>, so palette.deep becomes --sb-palette-deep. A reference
// such as "{palette.deep}" becomes var(--sb-palette-deep), so a role follows its palette colour.
// Font-family tokens with an org.sternbild.font-face extension also produce an @font-face rule.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const source = join(here, "tokens.json");
const target = join(root, "site", "design", "sternbild.css");

const tokens = JSON.parse(readFileSync(source, "utf8"));
const meta = tokens.$extensions?.["org.sternbild"] ?? {};
const prefix = meta.prefix ?? "sb";

// ---- Collect tokens, inheriting $type from the nearest group. ----------------------------
const list = [];
const byPath = new Map();
(function walk(node, path, type) {
  const ownType = node.$type ?? type;
  if ("$value" in node) {
    const token = { path, type: ownType, value: node.$value, ext: node.$extensions ?? {} };
    list.push(token);
    byPath.set(path.join("."), token);
    return;
  }
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith("$") || typeof child !== "object" || child === null) continue;
    walk(child, [...path, key], ownType);
  }
})(tokens, [], undefined);

const varName = path => `--${prefix}-${path.join("-")}`;
const isAlias = v => typeof v === "string" && /^\{[^}]+\}$/.test(v);
const aliasTarget = v => {
  const token = byPath.get(v.slice(1, -1));
  if (!token) throw new Error(`Unknown reference ${v}`);
  return token;
};
const refOrValue = (v, type) => (isAlias(v) ? `var(${varName(aliasTarget(v).path)})` : format(v, type, {}));

// ---- Format one value as CSS. ----------------------------------------------------------
const genericFamilies = new Set(["serif", "sans-serif", "monospace", "cursive", "fantasy", "system-ui",
  "ui-serif", "ui-sans-serif", "ui-monospace", "ui-rounded", "-apple-system", "BlinkMacSystemFont"]);

function format(value, type, ext) {
  const css = ext["org.sternbild.css"] ?? {};
  if (css.value !== undefined) return css.value;
  if (isAlias(value)) return `var(${varName(aliasTarget(value).path)})`;
  switch (type) {
    case "color": {
      if (typeof value === "string") return value;
      const alpha = value.alpha ?? 1;
      if (value.hex && alpha === 1) return value.hex;
      const [r, g, b] = value.components.map(c => Math.round(c * 255));
      return alpha === 1 ? `rgb(${r} ${g} ${b})` : `rgb(${r} ${g} ${b} / ${alpha})`;
    }
    case "dimension":
    case "duration":
      return typeof value === "string" ? value : `${value.value}${value.unit}`;
    case "number":
      return css.unit ? `${value}${css.unit}` : String(value);
    case "fontWeight":
      return String(value);
    case "fontFamily":
      return (Array.isArray(value) ? value : [value])
        .map(f => (genericFamilies.has(f) ? f : `"${f}"`)).join(", ");
    case "cubicBezier":
      return `cubic-bezier(${value.join(", ")})`;
    case "gradient": {
      const stops = value.map(s => `${refOrValue(s.color, "color")} ${+(s.position * 100).toFixed(2)}%`).join(", ");
      const fn = css.function ?? "linear-gradient";
      return css.geometry ? `${fn}(${css.geometry}, ${stops})` : `${fn}(${stops})`;
    }
    default:
      throw new Error(`No CSS format for type ${type}`);
  }
}

// Number tokens take their unit from their group's extension (tracking is in em).
function groupExt(path) {
  let node = tokens, ext = {};
  for (const key of path.slice(0, -1)) {
    node = node[key];
    if (node.$extensions?.["org.sternbild.css"]) ext = { ...ext, ...node.$extensions["org.sternbild.css"] };
  }
  return ext;
}

// ---- Emit. ----------------------------------------------------------------------------
const out = [];
out.push(`/* Sternbild design tokens ${meta.version ? `${meta.version} ` : ""}*/`);
out.push("/* Generated by design/build.mjs from design/tokens.json. Do not edit by hand. */");
out.push("");

for (const t of list) {
  const face = t.ext["org.sternbild.font-face"];
  if (t.type !== "fontFamily" || !face) continue;
  const file = join(root, face.file);
  if (!existsSync(file)) throw new Error(`Font file missing: ${face.file}`);
  const family = Array.isArray(t.value) ? t.value[0] : t.value;
  out.push("@font-face {");
  out.push(`  font-family: "${family}";`);
  out.push(`  src: url("${relative(dirname(target), file).split("\\").join("/")}") format("${face.format}");`);
  out.push(`  font-weight: ${face.weight ?? 400};`);
  out.push(`  font-style: ${face.style ?? "normal"};`);
  out.push("  font-display: swap;");
  out.push("}");
  out.push("");
}

out.push(":root {");
let group = null;
for (const t of list) {
  if (t.path[0] !== group) {
    if (group !== null) out.push("");
    group = t.path[0];
    out.push(`  /* ${group} */`);
  }
  const ext = { ...groupExt(t.path), ...(t.ext["org.sternbild.css"] ?? {}) };
  const value = isAlias(t.value) && ext.value === undefined
    ? `var(${varName(aliasTarget(t.value).path)})`
    : format(t.value, t.type, { "org.sternbild.css": ext });
  out.push(`  ${varName(t.path)}: ${value};`);
}
out.push("}");
out.push("");

const css = out.join("\n");

if (process.argv.includes("--check")) {
  const current = existsSync(target) ? readFileSync(target, "utf8") : "";
  if (current !== css) {
    console.error(`${relative(root, target)} is out of date. Run: node design/build.mjs`);
    process.exit(1);
  }
  console.log(`${relative(root, target)} is up to date (${list.length} tokens).`);
} else {
  writeFileSync(target, css);
  console.log(`Wrote ${relative(root, target)} (${list.length} tokens).`);
}
